print("Please pick a five letter word: ")
import random

# Pick a word at random
word_list = ["crate","synth","nymph","paper","court","kelps","count","flash","magic","adieu","inbox","greek","hotel","shape","turbo","curve","queue","hazel","cacti","moles","goats","leach"]
hidden_word = random.choice(word_list)


# Guess a word
guess_word = input()
output = ""

# First letter (in python, counting starts at 0 not 1)
if guess_word[0] == hidden_word[0]:
    output += "🟩"
elif guess_word[0] in hidden_word:
    output += "🟨"
else:
    output += "⬛"

# Second letter 
if guess_word[1] == hidden_word[1]:
    output += "🟩"
elif guess_word[1] in hidden_word:
    output += "🟨"
else:
    output += "⬛"

# third letter 
if guess_word[2] == hidden_word[2]:
    output += "🟩"
elif guess_word[2] in hidden_word:
    output += "🟨"
else:
    output += "⬛"

# fourth letter 
if guess_word[2] == hidden_word[2]:
    output += "🟩"
elif guess_word[2] in hidden_word:
    output += "🟨"
else:
    output += "⬛"

# fifth letter 
if guess_word[4] == hidden_word[4]:
    output += "🟩"
elif guess_word[4] in hidden_word:
    output += "🟨"
else:
    output += "⬛"


# Result
print(output)
if output == "🟩🟩🟩🟩🟩":
    print("You win")

